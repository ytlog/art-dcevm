runnable_jni::Result With(JNIEnv* env,jobject root,runnable_jni::Operation operation,void* data) {
 assert(env==&jni&&root==thread&&!closed);
 if(mode=="pending-after-read")pending=true;
 runnable_jni::Context context{reinterpret_cast<void*>(0x9900),env,&vm};
 return operation(context,data)?runnable_jni::Result::kSuccess:runnable_jni::Result::kOperationRejected;
}
